"""Render repository help from the same JSON embedded by the application; no dependencies."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Fail if the generated Markdown differs")
parser.add_argument("--sync-contracts", type=Path, help="Refresh signature snapshots from a reviewed runtime catalog export")
args = parser.parse_args()
if args.check and args.sync_contracts:
    parser.error("--check cannot modify signature snapshots")
# Hash reviewed JSON in canonical UTF-8/LF form so checkout autocrlf does not
# make the generated reference stale on another platform. This is docs only.
source = (root / "docs/script-api-reference.json").read_text(encoding="utf-8").encode("utf-8")
reference = json.loads(source)
if args.sync_contracts:
    exported = json.loads(args.sync_contracts.read_text(encoding="utf-8"))
    if exported.get("ApiVersion") != reference["ApiVersion"] or sorted(exported["SupportedTypes"]) != sorted(reference["SupportedTypes"]):
        raise SystemExit("Runtime catalog classification/API version differs; review it before syncing.")
    entries = {entry["Id"]: entry for entry in exported["Entries"]}
    if set(entries) != {entry["Id"] for entry in reference["Entries"]}:
        raise SystemExit("Runtime topic inventory differs; rebuild the reviewed catalog before syncing.")
    for entry in reference["Entries"]:
        actual = entries[entry["Id"]]
        if sorted(entry["Members"]) != sorted(actual["Members"]) or bool(entry.get("IsInfrastructure")) != bool(actual.get("IsInfrastructure")):
            raise SystemExit("Runtime member classification differs: " + entry["Id"])
        if entry["Members"] or entry.get("IsInfrastructure"):
            entry["Signature"] = actual["ExactSignature"]
    source = (json.dumps(reference, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    (root / "docs/script-api-reference.json").write_bytes(source)
lines = ["# Script API Reference", "", "<!-- Generated by build/WriteScriptApiReference.py. Edit script-api-reference.json. -->", "",
         f"Reference version {reference['Version']} · scripting API {reference['ApiVersion']} · available offline in Help → Script API Reference.", "",
         f"Source SHA-256: `{hashlib.sha256(source).hexdigest()}`.", "", reference["Scope"], "",
         "Signatures below are a verified snapshot of declared runtime contracts. The integrated reference derives exact signatures from the ScriptHost facade assembly; Copy API catalog JSON exports the complete machine-readable catalog. Permanent tests require this snapshot to match that runtime inventory.", "",
         "In the Script Editor, F1 looks up the supported API symbol at the cursor. Ctrl+Space explicitly opens documented facade completion; Ctrl+Shift+Space shows invocation signatures. No automatic popups, script execution or source mutation occur during lookup. Ordinary .NET APIs and arbitrary user code are outside facade completion.", "",
         "Search `starter` in the application to find the six editable starter examples. Built-in de-identification presets remain in the Script Library; duplicate them to customize their complete policies.", ""]
for category in dict.fromkeys(e["Category"] for e in reference["Entries"]):
    lines += [f"## {category}", ""]
    for entry in (e for e in reference["Entries"] if e["Category"] == category):
        lines += [f"### {entry['Title']}", "", entry["Description"], "", "```csharp", entry["Signature"], "```", "",
                  "**Parameters:** " + entry["Parameters"], "", "**Returns:** " + entry["Returns"], "",
                  "**Null and missing values:** " + entry["NullBehavior"], "", "**Mutation:** " + entry["Mutation"], "",
                  "**Errors:** " + entry["Errors"], "", "**Execution modes:** " + entry["Modes"], "",
                  "**Limits and important behavior:** " + entry["Limitations"], "", "```csharp", entry["Example"], "```", ""]
        lines += ["Related topic IDs: " + ", ".join("`" + topic + "`" for topic in entry["Related"]) + ".", ""]
        if entry["TemplateName"]:
            lines += ["Starter: **" + entry["TemplateName"] + "**. Use Create editable script in the reference.", ""]
lines += ["## Host infrastructure outside the supported authoring facade", ""]
for name, reason in reference["InfrastructureTypes"].items():
    lines += [f"- `{name}`: {reason}"]
text = "\n".join(lines) + "\n"
destination = root / "docs/script-api-reference.md"
if args.check:
    if not destination.exists() or destination.read_text(encoding="utf-8") != text:
        raise SystemExit("Script API Reference Markdown is stale; run build/WriteScriptApiReference.py")
    print("Script API Reference Markdown matches the authoritative embedded JSON.")
else:
    destination.write_text(text, encoding="utf-8", newline="\n")
    print("Rendered Script API Reference Markdown.")
